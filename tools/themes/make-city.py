# The City blue theme: the Watermelon theme (data-theme="teal": the teal of the logo, the pink status bar,
# the yellow marks, the content on white) with the palette of an urban plan on blueprint blue — a deep
# cobalt frame, coral paths, white lines. The same proportions of white and colour: every rule of the
# Watermelon theme is copied for [data-palette="city"] (set together with data-theme="teal") with its
# colours swapped; a few rules of its own follow (OWN: the status bar on white). Run after changing the Watermelon theme:  python3 tools/themes/make-city.py
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'src', 'workbench', 'browser', 'media', 'workbench.css')
OUT = os.path.join(ROOT, 'src', 'workbench', 'browser', 'media', 'theme-city.css')

# Watermelon → City blue (white text keeps 4.5:1 or more on every blue; dark text on the coral)
COLORS = {
    '#0187a3': '#1b3f94',   # the frame (title bar, activity bar), the accent on white
    '#017893': '#173784',   # the frame, a step deeper
    '#0a7f98': '#23479c', '#016b84': '#14317a', '#01657c': '#122d72', '#016f86': '#15357f',
    '#1d8aa2': '#3555a3', '#3aa2b9': '#5070b6',
    '#d8f1f6': '#dde6f7', '#b4e2eb': '#b9c9ec',
    '#062a33': '#0b1d45',   # dark text on the light buttons of the frame
    '#df6f95': '#f06b5f',   # the pink → the coral of the paths (status bar, selection, Limbo)
    '#eb94b3': '#f59188', '#e98bad': '#f58a80', '#c95a80': '#d4554a', '#c2456f': '#c94236',
    '#ffd3e2': '#ffd8d3', '#ffb3cd': '#ffbab2', '#fdeef3': '#fdecea',
    '#2b0816': '#2d0c08', '#3d0f22': '#3f140e', '#4f1a30': '#511d15',
    '#ff7ab6': '#ff8a7f', '#ff97c6': '#ffa59c', '#ff5ca6': '#ff7b6f',
    '#eecd25': '#f06b5f', '#f6db4d': '#f58a80',   # the yellow of the frame → coral too
}
RGBA = {
    'rgba(1, 135, 163,': 'rgba(27, 63, 148,',
    'rgba(43, 8, 22,': 'rgba(45, 12, 8,',
    'rgba(255, 122, 182,': 'rgba(255, 138, 127,',
    'rgba(223, 111, 149,': 'rgba(240, 107, 95,',
}

def split_selectors(sel):
    # commas outside parentheses only (:is(a, b) stays whole)
    parts, depth, cur = [], 0, ''
    for ch in sel:
        if ch == '(': depth += 1
        elif ch == ')': depth -= 1
        if ch == ',' and depth == 0: parts.append(cur.strip()); cur = ''
        else: cur += ch
    parts.append(cur.strip())
    return parts

def recolor(s):
    for a, b in RGBA.items(): s = s.replace(a, b)
    return re.sub(r'#[0-9a-fA-F]{6}\b', lambda m: COLORS.get(m.group(0).lower(), m.group(0)), s)

css = open(SRC, encoding='utf-8').read()
css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
out = []
def walk(text, wrap=None):
    i = 0
    while i < len(text):
        j = text.find('{', i)
        if j < 0: break
        sel = text[i:j].strip()
        # the block: matching braces
        depth, k = 0, j
        while k < len(text):
            if text[k] == '{': depth += 1
            elif text[k] == '}':
                depth -= 1
                if depth == 0: break
            k += 1
        body = text[j + 1:k]
        if sel.startswith('@media') or sel.startswith('@supports') or sel.startswith('@container'):
            walk(body, sel)
        elif '[data-theme="teal"]' in sel and not sel.startswith('@'):
            parts = [p for p in split_selectors(sel) if '[data-theme="teal"]' in p and ':not([data-theme="teal"])' not in p]
            if parts:
                new_sel = ', '.join(p.replace('[data-theme="teal"]', '[data-palette="city"]') for p in parts)
                rule = f'{new_sel} {{{recolor(body)}}}'
                out.append(f'{wrap} {{ {rule} }}' if wrap else rule)
        i = k + 1
walk(css)
# City blue's own rules, after the copied ones (the same selectors: the later wins)
OWN = [
    # the status bar in a pale blue-grey (set apart from the white content), its words in cobalt (Watermelon keeps its pink bar); busy still turns it coral
    ':root[data-palette="city"] .part.statusbar { --bg-status: #f3f6fc; --bg-elevated: #e4eaf6; '
    '--border: rgba(27, 63, 148, 0.22); --border-strong: rgba(27, 63, 148, 0.34); --text-primary: #1b3f94; '
    '--text-secondary: #24488f; --text-muted: #5a6f9f; --hover: rgba(27, 63, 148, 0.07); '
    '--active: rgba(27, 63, 148, 0.12); --accent: #d9473b; --brand-magenta: #f06b5f; color-scheme: light; }',
]
out += OWN
head = ('/* GENERATED by tools/themes/make-city.py from workbench.css — do not edit: change the Watermelon theme\n'
        '   ([data-theme="teal"]) or the colours in the tool, and run it again.\n'
        '   City blue: the cobalt of a blueprint, coral paths, white — in the proportions of Watermelon. */\n')
open(OUT, 'w', encoding='utf-8').write(head + '\n'.join(re.sub(r'\s+', ' ', r).strip() for r in out) + '\n')
print(f'{OUT}: {len(out)} rules')
